export function getTransversalEntitiesForCountry(
  isoCode: string | null | undefined
): TransversalEntityMeta[] {
  if (!isoCode) return [];
  const upper = isoCode.toUpperCase();
  return TRANSVERSAL_ENTITIES_META.filter((item) => item.countryIsos.includes(upper));
}
